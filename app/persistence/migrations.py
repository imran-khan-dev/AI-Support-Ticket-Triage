"""Forward-only schema migrations for PostgreSQL.

PostgreSQL has no ``PRAGMA user_version`` equivalent, so the applied schema
version is tracked in a ``schema_migrations`` table. The runner:

* takes a session-level advisory lock, so several application instances
  starting at the same time cannot migrate the database concurrently;
* applies each pending migration inside its own transaction, which makes a
  migration atomic - PostgreSQL has transactional DDL, so a failed migration
  leaves neither the schema nor the recorded version changed;
* never edits an applied migration. Later migrations are appended instead.
"""

from __future__ import annotations

import psycopg

# ---------------------------------------------------------------------------
# Migration 1: initial schema
# ---------------------------------------------------------------------------
#
# sessions     - one row per conversation (server-issued id)
# messages     - ordered transcript rows belonging to a session
# memories     - derived long-term memory (not authoritative; a later
#                milestone populates it and adds the search index)
# actions      - approval state machine for gated tool calls
# approvers    - identities allowed to approve actions
# audit_events - append-only audit trail
#
MIGRATION_1 = """
CREATE TABLE sessions (
    id          UUID PRIMARY KEY,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    status      TEXT NOT NULL DEFAULT 'open',
    ticket_id   TEXT,
    title       TEXT,
    next_seq    INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT sessions_status_check
        CHECK (status IN ('open', 'closed')),
    CONSTRAINT sessions_next_seq_check
        CHECK (next_seq >= 1)
);

CREATE TABLE messages (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id     UUID NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    seq            INTEGER NOT NULL,
    role           TEXT NOT NULL,
    content        TEXT NOT NULL,
    call_id        TEXT,
    tool_name      TEXT,
    correlation_id UUID,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT messages_role_check
        CHECK (role IN ('user', 'assistant', 'tool', 'system')),
    CONSTRAINT messages_session_seq_key
        UNIQUE (session_id, seq)
);

CREATE INDEX ix_messages_session_seq ON messages (session_id, seq);
CREATE INDEX ix_messages_correlation ON messages (correlation_id);

CREATE TABLE memories (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    UUID NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    kind          TEXT NOT NULL,
    content       TEXT NOT NULL,
    source_msg_id BIGINT REFERENCES messages(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT memories_kind_check
        CHECK (kind IN ('summary', 'fact', 'preference', 'outcome'))
);

CREATE INDEX ix_memories_session ON memories (session_id, created_at);

CREATE TABLE actions (
    id               UUID PRIMARY KEY,
    request_key      TEXT NOT NULL UNIQUE,
    session_id       UUID REFERENCES sessions(id) ON DELETE SET NULL,
    correlation_id   UUID NOT NULL,
    tool_name        TEXT NOT NULL,
    effect_class     TEXT NOT NULL,
    args             TEXT NOT NULL,
    args_hash        TEXT NOT NULL,
    state            TEXT NOT NULL,
    requested_by     TEXT NOT NULL,
    requested_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    decided_by       TEXT,
    decided_at       TIMESTAMPTZ,
    decision_reason  TEXT,
    execution_status TEXT,
    execution_error  TEXT,
    executed_by      TEXT,
    executed_at      TIMESTAMPTZ,
    CONSTRAINT actions_state_check
        CHECK (state IN ('pending', 'approved', 'rejected', 'executed')),
    CONSTRAINT actions_execution_status_check
        CHECK (execution_status IS NULL
               OR execution_status IN ('success', 'failure'))
);

CREATE INDEX ix_actions_state ON actions (state, requested_at);
CREATE INDEX ix_actions_session ON actions (session_id);

CREATE TABLE approvers (
    id           UUID PRIMARY KEY,
    display_name TEXT NOT NULL,
    role         TEXT NOT NULL,
    token_hash   TEXT NOT NULL,
    active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT approvers_role_check
        CHECK (role IN ('agent', 'supervisor', 'billing_admin', 'admin'))
);

CREATE TABLE audit_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id       UUID NOT NULL UNIQUE,
    correlation_id UUID NOT NULL,
    session_id     UUID,
    ticket_id      TEXT,
    actor_type     TEXT NOT NULL,
    actor_id       TEXT,
    action         TEXT NOT NULL,
    target         TEXT,
    decision       TEXT,
    outcome        TEXT,
    payload        TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT audit_events_actor_type_check
        CHECK (actor_type IN ('agent', 'customer', 'approver', 'system')),
    CONSTRAINT audit_events_decision_check
        CHECK (decision IS NULL OR decision IN ('approved', 'rejected')),
    CONSTRAINT audit_events_outcome_check
        CHECK (outcome IS NULL
               OR outcome IN ('success', 'failure', 'blocked', 'denied'))
);

CREATE INDEX ix_audit_events_correlation ON audit_events (correlation_id);
CREATE INDEX ix_audit_events_session ON audit_events (session_id, created_at);
CREATE INDEX ix_audit_events_actor ON audit_events (actor_id, created_at);
CREATE INDEX ix_audit_events_action ON audit_events (action, created_at);

CREATE OR REPLACE FUNCTION audit_events_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_events is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_events_append_only
    BEFORE UPDATE OR DELETE ON audit_events
    FOR EACH ROW EXECUTE FUNCTION audit_events_append_only();
"""

# Ordered list of (version, name, sql) triples. Never edit an applied
# migration; append a new numbered entry instead.
MIGRATIONS: list[tuple[int, str, str]] = [
    (1, "initial_schema", MIGRATION_1),
]

#: Arbitrary key for the advisory lock that serializes migration runs.
MIGRATION_LOCK_KEY = 0x7A11_3E01

_BOOTSTRAP_SQL = """
CREATE TABLE IF NOT EXISTS schema_migrations (
    version    INTEGER PRIMARY KEY,
    name       TEXT NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
)
"""


def bootstrap(conn: psycopg.Connection) -> None:
    """Create the migration bookkeeping table if it does not exist."""
    with conn.transaction():
        conn.execute(_BOOTSTRAP_SQL)


def applied_versions(conn: psycopg.Connection) -> set[int]:
    """Return the migration versions already applied to this database."""
    rows = conn.execute("SELECT version FROM schema_migrations").fetchall()
    return {int(row["version"]) for row in rows}


def current_version(conn: psycopg.Connection) -> int:
    """Return the highest applied migration version.

    A database that has never been migrated reports ``0``.
    """
    try:
        row = conn.execute(
            "SELECT COALESCE(MAX(version), 0) AS version FROM schema_migrations"
        ).fetchone()
    except psycopg.errors.UndefinedTable:
        conn.rollback()
        return 0
    return int(row["version"]) if row is not None else 0


def apply_migrations(conn: psycopg.Connection) -> list[int]:
    """Apply every pending migration and return the versions that were applied.

    Applying migrations to an up-to-date database is a no-op and returns an
    empty list, so initialization is idempotent.
    """
    # A session-level advisory lock keeps concurrent instances from migrating
    # the same database at the same time. It is released in the finally block.
    conn.execute("SELECT pg_advisory_lock(%s)", (MIGRATION_LOCK_KEY,))
    conn.commit()
    try:
        bootstrap(conn)
        already_applied = applied_versions(conn)
        newly_applied: list[int] = []
        for version, name, script in MIGRATIONS:
            if version in already_applied:
                continue
            with conn.transaction():
                # PostgreSQL has transactional DDL: the script and the version
                # record commit together or not at all.
                conn.execute(script)
                conn.execute(
                    "INSERT INTO schema_migrations (version, name) VALUES (%s, %s)",
                    (version, name),
                )
            newly_applied.append(version)
        return newly_applied
    finally:
        conn.execute("SELECT pg_advisory_unlock(%s)", (MIGRATION_LOCK_KEY,))
        conn.commit()
