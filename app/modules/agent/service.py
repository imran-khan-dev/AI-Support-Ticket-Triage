"""Session lifecycle and transcript persistence for the agent endpoint.

This module sits between the HTTP route and the persistence layer. It owns two
responsibilities:

1. Deciding which session a run belongs to. Session ids are generated by the
   server; a client-supplied id is only accepted when it identifies a session
   that actually exists and is usable.
2. Turning the outcome of an agent run into an ordered transcript.

The transcript is stored for later retrieval, and the stored turns of a
session are replayed into a continuing run, bounded by the configured
maximum history size.
"""

from __future__ import annotations

import json
import logging
import uuid
from typing import Any, Iterable

import psycopg

from app.agent_core.agent import AgentResult
from app.core.config import (
    DEFAULT_MAX_HISTORY_MESSAGES,
    DEFAULT_MAX_MEMORY_CHARS,
    DEFAULT_MAX_MEMORY_ITEMS,
)
from app.modules.agent.history import load_history_items
from app.modules.agent.memory import build_memory_items
from app.persistence.db import Database
from app.persistence.models import (
    ROLE_ASSISTANT,
    ROLE_SYSTEM,
    ROLE_TOOL,
    ROLE_USER,
    SESSION_STATUS_CLOSED,
    MessageDraft,
)
from app.persistence.repository import (
    append_messages,
    create_session,
    get_session,
)

logger = logging.getLogger("agent.service")


class StorageError(RuntimeError):
    """Raised when the session store cannot be read or written."""


class InvalidSessionIdError(ValueError):
    """Raised when a client-supplied session id is not a well-formed id."""


class SessionNotFoundError(LookupError):
    """Raised when a client-supplied session id does not identify a session."""


class SessionClosedError(RuntimeError):
    """Raised when a run is submitted against a closed session."""


def is_valid_session_id(value: Any) -> bool:
    """Return True when the value is a well-formed session id."""
    if not isinstance(value, str):
        return False
    try:
        uuid.UUID(value)
    except (ValueError, AttributeError, TypeError):
        return False
    return True


def canonical_session_id(value: str) -> str:
    """Return the canonical form of a session id."""
    return str(uuid.UUID(value))


def prepare_session_store(db: Database) -> None:
    """Make sure the schema exists before a run touches the session store."""
    try:
        db.ensure_initialized()
    except psycopg.Error as exc:
        raise StorageError("The session store is unavailable.") from exc


def resolve_session_id(db: Database, requested_session_id: str | None) -> str:
    """Return the session id a run belongs to.

    When no id is supplied a new session is created. When an id is supplied
    it must identify an existing, open session; an unknown or malformed id is
    rejected rather than trusted.
    """
    try:
        if requested_session_id is None:
            return create_session(db).id

        candidate = str(requested_session_id).strip()
        if not is_valid_session_id(candidate):
            raise InvalidSessionIdError(
                "The session id must be a UUID."
            )

        session_id = canonical_session_id(candidate)
        session = get_session(db, session_id)
        if session is None:
            raise SessionNotFoundError(session_id)
        if session.status == SESSION_STATUS_CLOSED:
            raise SessionClosedError(session_id)
        return session_id
    except psycopg.Error as exc:
        raise StorageError("The session store is unavailable.") from exc


def load_session_history(
    db: Database,
    session_id: str,
    *,
    max_messages: int = DEFAULT_MAX_HISTORY_MESSAGES,
    exclude_correlation_ids: Iterable[str] | None = None,
) -> list[dict[str, Any]]:
    """Return the prior turns of a session as provider input items.

    The transcript is read before the run starts, so the message of the
    current run is not part of the history. The caller passes the id of the
    run it is about to start in ``exclude_correlation_ids``, so the messages
    of that run are left out as well.

    A storage failure is reported as a :class:`StorageError`, like the other
    reads of the session store.
    """
    try:
        return load_history_items(
            db,
            session_id,
            max_messages=max_messages,
            exclude_correlation_ids=exclude_correlation_ids,
        )
    except psycopg.Error as exc:
        raise StorageError("The session store is unavailable.") from exc


def load_session_memory(
    db: Database,
    session_id: str,
    message: str,
    *,
    max_items: int = DEFAULT_MAX_MEMORY_ITEMS,
    max_chars: int = DEFAULT_MAX_MEMORY_CHARS,
) -> list[dict[str, Any]]:
    """Return the memory context of a run as provider input items.

    Recalling a memory is best-effort. The support answer is the primary
    result of a request, so a storage failure is logged and the run
    continues without memory context instead of failing the request.

    Only storage errors are caught. A connection failure, a failed query,
    and an exhausted connection pool are all reported by PostgreSQL as a
    ``psycopg.Error``; a programming error is not hidden.
    """
    try:
        return build_memory_items(
            db,
            session_id,
            message,
            max_items=max_items,
            max_chars=max_chars,
        )
    except psycopg.Error:
        logger.exception(
            "Failed to recall the memories of session %s", session_id
        )
        return []


def build_transcript(message: str, result: AgentResult) -> list[MessageDraft]:
    """Build the ordered transcript of a single agent run.

    The order is: the user message, then one assistant tool-call record and
    one tool result per tool call in execution order, then the final answer
    (or the safe error message when the run did not produce an answer).
    """
    drafts: list[MessageDraft] = [
        MessageDraft(role=ROLE_USER, content=message),
    ]

    for call in result.tool_calls or []:
        tool_name = call.get("tool")
        call_id = call.get("call_id")
        arguments = call.get("arguments") or {}
        drafts.append(
            MessageDraft(
                role=ROLE_ASSISTANT,
                content=json.dumps(
                    {"tool": tool_name, "arguments": arguments},
                    sort_keys=True,
                    default=str,
                ),
                call_id=call_id,
                tool_name=tool_name,
            )
        )
        drafts.append(
            MessageDraft(
                role=ROLE_TOOL,
                content=json.dumps(
                    call.get("result") or {},
                    sort_keys=True,
                    default=str,
                ),
                call_id=call_id,
                tool_name=tool_name,
            )
        )

    if result.answer:
        drafts.append(MessageDraft(role=ROLE_ASSISTANT, content=result.answer))
    elif result.error:
        drafts.append(MessageDraft(role=ROLE_SYSTEM, content=result.error))

    return drafts


def persist_agent_run(
    db: Database,
    session_id: str,
    message: str,
    result: AgentResult,
    correlation_id: str | None = None,
) -> bool:
    """Store the transcript of an agent run.

    ``correlation_id`` identifies the run. The caller can pass the id of the
    run it is about to start, so that the same id can be used to keep the
    messages of that run out of the history of a later one.

    Returns ``True`` when the transcript was written and ``False`` when it
    could not be. A storage failure is logged rather than raised: the agent's
    answer is the primary result of the request and must not be discarded
    because the transcript could not be written. The caller reports the
    outcome so the client can tell a stored transcript from a lost one.
    """
    try:
        append_messages(
            db,
            session_id,
            build_transcript(message, result),
            correlation_id=correlation_id or str(uuid.uuid4()),
        )
    except Exception:
        # Deliberately broad: losing the transcript must never discard the
        # agent's answer, which is the primary result of the request.
        logger.exception(
            "Failed to persist the transcript for session %s", session_id
        )
        return False
    return True
